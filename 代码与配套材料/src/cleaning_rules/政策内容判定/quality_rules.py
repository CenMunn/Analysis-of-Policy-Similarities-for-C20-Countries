import re
def risk_flags(t):
    flags=[]
    patterns=[
        ('评价或效果仍混入',r'这种做法是错误|全面倒退|富有远见|反应冷淡|是个问号|动了谁的奶酪|更让人怀疑|决心不可谓不大|推广带来.{0,35}好处|引发了不小波澜|否定[^。；]{0,35}并不是否定|以期成为[^。；]{0,35}领导者|这有利于提振|影响重大'),
        ('网页模板或章节噪声混入',r'微信公众号|微信规则改版|公众号添加|图片来源：|污染防治资讯头条|投资聚焦|^\s*\d+[.．]\d+[.．]'),
        ('执行历史或法定程序尚未分清',r'还未获得国会认可|从未被实施|终于要被.{0,10}废掉'),
        ('新闻机构与官方印发机关冲突',r'国家能源局发布《新能源汽车产业发展规划'),
        ('行业倡议与公共政策身份待核',r'英国氢能网络计划'),
        ('报道年代与政策身份冲突',r'2006年奥巴马.{0,10}清洁能源计划'),
        ('同日同政策金额冲突_待一手核验',r'法国2030投资计划.{0,30}斥资(?:90|19)亿欧元'),
        ('气候政策名称与程序含糊',r'备战2020年总统大选再下|情景三：重建更好法案'),
    ]
    for label,p in patterns:
        if re.search(p,t):flags.append(label)
    if re.fullmatch(r'\s*[“《][^”》]+[”》][;；。]?\s*',t):flags.append('只有政策标题，没有措施断言')
    if re.search(r'计划[”》]?.{0,10}助力.{0,30}碳中和$',t):flags.append('政策标题及效果引导，无具体措施')
    return flags
